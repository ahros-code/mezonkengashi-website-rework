const TALIM_SHIFT = -106;

type Tone = { left?: string; right?: string; className?: string; title?: string };

/** The open book. Pass one colour to both leaves for a foil stamp. */
export function TalimLeaves({ left = "#003A64", right = "#F8B700", className, title }: Tone) {
  return (
    <svg
      viewBox="180 -1 92 73"
      className={className}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      <path d={LEFT_LEAF} fill={left} />
      <path d={RIGHT_LEAF} fill={right} />
    </svg>
  );
}

/** One leaf of the book on its own, so the two can be hinged at the spine. */
export function TalimLeaf({ side, fill, className }: { side: "left" | "right"; fill: string; className?: string }) {
  return (
    <svg
      viewBox={side === "left" ? "180.5 -1 46 73" : "225.2 -1 46 73"}
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      <path d={side === "left" ? LEFT_LEAF : RIGHT_LEAF} fill={fill} />
    </svg>
  );
}

